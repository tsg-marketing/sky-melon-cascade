const BRAND_RULES: { re: RegExp; brand: string }[] = [
  { re: /\bAGK\b/i, brand: "AGK Kronawitter" },
  { re: /\bSF-\d/i, brand: "Suntok" },
  { re: /\bXQ/i, brand: "Daribo" },
  { re: /skinex|cortex/i, brand: "Nock" },
  { re: /ebro/i, brand: "EBRO" },
];

export function fishBrand(item: CatalogItem): string {
  const raw = (item.brand || "").trim();
  if (raw) return raw.replace(/\s*\(.*\)\s*$/, "");
  const hit = BRAND_RULES.find((r) => r.re.test(item.name || ""));
  return hit ? hit.brand : "Другие";
}

